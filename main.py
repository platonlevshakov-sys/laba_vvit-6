# sys нужен для передачи аргументов командной строки в приложение и корректного закрытия
import sys

# QApplication управляет работой всего графического приложения и циклом событий
from PyQt6.QtWidgets import QApplication

# Импортируем наш собственный класс главного окна из файла main_window.py
from main_window import MainWindow


def main():
    # Создаём главный объект приложения PyQt (обязателен для любого GUI на Qt)
    # sys.argv передаёт системные параметры запуска
    app = QApplication(sys.argv)

    # Создаём экземпляр нашего окна (срабатывает конструктор __init__ в MainWindow)
    window = MainWindow()

    # Делаем окно видимым на экране (по умолчанию после создания оно скрыто)
    window.show()

    # app.exec() запускает бесконечный цикл обработки событий (Event Loop).
    # Программа не завершается, а постоянно слушает клики, ввод текста и т.д.
    # sys.exit() гарантирует чистый выход из ОС при закрытии окна
    sys.exit(app.exec())


# Проверка: выполняем main() только если файл запущен напрямую, а не импортирован
if __name__ == "__main__":
    main()